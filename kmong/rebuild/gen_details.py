def main(only: list[int]):
    import time

    targets = only or sorted(SPECS)
    for n, i in enumerate(targets):
        name, spec = SPECS[i]
        prompt = STYLE + "\n\n[이 이미지의 텍스트·레이아웃 명세]\n" + spec
        for attempt in range(4):
            try:
                out = vertex_image(prompt, str(HERE / f"{name}.png"),
                                   model="gemini-3-pro-image", aspect_ratio="4:3",
                                   reference_images=[str(REF)])
                print(f"[{i}/7] saved: {out}", flush=True)
                break
            except Exception as e:  # noqa: BLE001
                if "429" in str(e) and attempt < 3:
                    print(f"[{i}/7] 429 — {75}s 대기 후 재시도 ({attempt+1}/3)", flush=True)
                    time.sleep(75)
                else:
                    raise
        if n < len(targets) - 1:
            time.sleep(45)  # 분당 쿼터 보호


if __name__ == "__main__":
    main([int(a) for a in sys.argv[1:]])
